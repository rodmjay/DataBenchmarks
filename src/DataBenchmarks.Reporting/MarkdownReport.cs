using System.Text;
using DataBenchmarks.Core.Engines;
using DataBenchmarks.Scenarios;

namespace DataBenchmarks.Reporting;

/// Renders results as Markdown: a short "which approach wins" summary for the root README and
/// full tables for results/README.md.
public sealed class MarkdownReport(IReadOnlyList<ResultRecord> records, IReadOnlyList<LoadRecord> load)
{
    public const string StartMarker = "<!-- results:start -->";
    public const string EndMarker = "<!-- results:end -->";
    public const string DashboardUrl = "https://rodmjay.github.io/DataBenchmarks/";

    private static readonly Dictionary<string, string> EngineTitles = new()
    {
        ["sqlite"] = "SQLite",
        ["postgres"] = "PostgreSQL",
        ["sqlserver"] = "SQL Server",
        ["mysql"] = "MySQL",
    };

    private readonly List<string> _engines = EngineCatalog.Names
        .Where(e => records.Any(r => r.Engine == e) || load.Any(r => r.Engine == e))
        .ToList();

    private readonly List<IGrouping<string, ResultRecord>> _scenarios = records
        .GroupBy(r => r.ScenarioKey)
        .OrderBy(g => g.Key)
        .ToList();

    public string Summary()
    {
        var md = new StringBuilder();
        if (records.Count == 0)
        {
            md.AppendLine("_No results yet. Run `./bench publish` to produce them._");
            return md.ToString();
        }

        md.AppendLine("**Fastest single operation** per scenario and engine, and the fastest EF Core approach as a multiple of the hand-written ADO.NET baseline on the same engine (1.00× = as fast as raw ADO.NET; lower is better).");
        md.AppendLine();
        AppendHeader(md, "Scenario");
        foreach (var scenario in _scenarios)
        {
            md.Append($"| [{scenario.Key}](results/README.md#{Anchor(scenario.Key)}) |");
            foreach (var engine in _engines)
            {
                var rows = scenario.Where(r => r.Engine == engine).ToList();
                if (rows.Count == 0)
                {
                    md.Append(" – |");
                    continue;
                }
                var fastest = rows.MinBy(r => r.MeanNs)!;
                var bestEf = rows.Where(r => r.Approach.StartsWith("Ef", StringComparison.Ordinal)).MinBy(r => r.MeanNs);
                md.Append($" **{fastest.Approach}** {Format.Time(fastest.MeanNs)}");
                if (bestEf is not null)
                {
                    md.Append($"<br>EF Core: {bestEf.Approach} {Ratio(bestEf, rows)}");
                }
                md.Append(" |");
            }
            md.AppendLine();
        }

        if (load.Count > 0)
        {
            md.AppendLine();
            md.AppendLine("**Highest throughput under high concurrency** (most operations per second, with p99 latency).");
            md.AppendLine();
            AppendHeader(md, "Scenario");
            foreach (var scenario in load.GroupBy(r => r.ScenarioKey).OrderBy(g => g.Key))
            {
                md.Append($"| {scenario.Key} |");
                foreach (var engine in _engines)
                {
                    var best = scenario.Where(r => r.Engine == engine && r.Level == "high" && r.Errors == 0).MaxBy(r => r.OpsPerSecond);
                    md.Append(best is null ? " – |" : $" **{best.Approach}** {Format.Throughput(best.OpsPerSecond)}<br>p99 {best.P99Ms:F1} ms |");
                }
                md.AppendLine();
            }
        }

        md.AppendLine();
        md.AppendLine($"Full tables with allocations, latency percentiles and every approach: [results/README.md](results/README.md) · Trends over time: [dashboard]({DashboardUrl})");
        md.AppendLine();
        md.AppendLine($"<sub>{RunLine()}</sub>");
        return md.ToString();
    }

    public string Full()
    {
        var md = new StringBuilder();
        md.AppendLine("# Results");
        md.AppendLine();
        md.AppendLine("> Generated by `./bench publish`. Do not edit by hand.");
        md.AppendLine();
        md.AppendLine("Single-operation cells show **mean time per operation · ratio to the ADO.NET baseline on that engine · bytes allocated per operation**; the fastest approach on each engine is in bold. Compare ratios within a column: absolute times depend on the machine.");
        md.AppendLine();
        md.AppendLine("## Runs");
        md.AppendLine();
        md.AppendLine("| Engine | Run (UTC) | Commit | Job | Dataset | Machine | Runtime |");
        md.AppendLine("|---|---|---|---|---|---|---|");
        foreach (var run in records.GroupBy(r => r.Engine).OrderBy(g => _engines.IndexOf(g.Key)))
        {
            var info = run.MaxBy(r => r.Run.RunAt)!.Run;
            md.AppendLine($"| {Title(run.Key)} | {info.RunAt:yyyy-MM-dd HH:mm} | `{info.Commit}` | {info.Job} | {info.Dataset} | {info.Processor} | {info.Runtime} |");
        }

        foreach (var category in _scenarios.GroupBy(s => s.First().Category))
        {
            md.AppendLine();
            md.AppendLine($"## {category.Key}");
            foreach (var scenario in category)
            {
                var first = scenario.First();
                var info = ScenarioCatalog.All.FirstOrDefault(s => s.Category == first.Category && s.Name == first.Scenario);
                md.AppendLine();
                md.AppendLine($"### {scenario.Key}");
                md.AppendLine();
                if (info?.Description is not null)
                {
                    md.AppendLine($"{info.Description} [Spec](../src/DataBenchmarks.Scenarios/Scenarios/{first.Category}/{first.Scenario}/README.md)");
                    md.AppendLine();
                }
                AppendHeader(md, "Approach");
                foreach (var approach in OrderedApproaches(scenario.Select(r => r.Approach)))
                {
                    md.Append($"| {approach} |");
                    foreach (var engine in _engines)
                    {
                        var rows = scenario.Where(r => r.Engine == engine).ToList();
                        var row = rows.FirstOrDefault(r => r.Approach == approach);
                        if (row is null)
                        {
                            md.Append(" – |");
                            continue;
                        }
                        var cell = $"{Format.Time(row.MeanNs)} · {Ratio(row, rows)} · {Format.Bytes(row.AllocatedBytes)}";
                        md.Append(row == rows.MinBy(r => r.MeanNs) ? $" **{cell}** |" : $" {cell} |");
                    }
                    md.AppendLine();
                }

                AppendLoad(md, load.Where(r => r.ScenarioKey == $"{first.Category}/{first.Scenario}").ToList());
            }
        }

        md.AppendLine();
        md.AppendLine("## Approaches");
        md.AppendLine();
        foreach (var (name, description) in Approaches.Descriptions)
        {
            md.AppendLine($"- **{name}**: {description}");
        }
        return md.ToString();
    }

    /// Replaces the generated block between the markers in a README, leaving the rest untouched.
    public static string Splice(string readme, string block)
    {
        var start = readme.IndexOf(StartMarker, StringComparison.Ordinal);
        var end = readme.IndexOf(EndMarker, StringComparison.Ordinal);
        if (start < 0 || end < start)
        {
            throw new InvalidOperationException($"README is missing the {StartMarker} / {EndMarker} markers.");
        }
        return readme[..(start + StartMarker.Length)] + "\n" + block + readme[end..];
    }

    private void AppendLoad(StringBuilder md, List<LoadRecord> rows)
    {
        if (rows.Count == 0)
        {
            return;
        }
        var levels = rows.OrderBy(r => r.Concurrency).Select(r => (r.Level, r.Concurrency)).Distinct().ToList();
        foreach (var engine in _engines.Where(e => rows.Any(r => r.Engine == e)))
        {
            md.AppendLine();
            md.AppendLine($"Under load on {Title(engine)}: **operations/s · p50 / p95 / p99 latency (ms) · errors**");
            md.AppendLine();
            md.AppendLine("| Approach | " + string.Join(" | ", levels.Select(l => $"{l.Level} ({l.Concurrency})")) + " |");
            md.AppendLine("|---|" + string.Concat(levels.Select(_ => "---|")));
            var engineRows = rows.Where(r => r.Engine == engine).ToList();
            foreach (var approach in OrderedApproaches(engineRows.Select(r => r.Approach)))
            {
                md.Append($"| {approach} |");
                foreach (var (level, _) in levels)
                {
                    var r = engineRows.FirstOrDefault(x => x.Approach == approach && x.Level == level);
                    if (r is null)
                    {
                        md.Append(" – |");
                        continue;
                    }
                    var cell = $"{Format.Throughput(r.OpsPerSecond)} · {r.P50Ms:F2} / {r.P95Ms:F2} / {r.P99Ms:F2} · {r.Errors}";
                    var best = engineRows.Where(x => x.Level == level).MaxBy(x => x.OpsPerSecond);
                    md.Append(r == best ? $" **{cell}** |" : $" {cell} |");
                }
                md.AppendLine();
            }
        }
    }

    private void AppendHeader(StringBuilder md, string first)
    {
        md.AppendLine($"| {first} | " + string.Join(" | ", _engines.Select(Title)) + " |");
        md.AppendLine("|---|" + string.Concat(_engines.Select(_ => "---|")));
    }

    private string RunLine()
    {
        var runs = records.Select(r => r.Run).DistinctBy(r => r.Id).ToList();
        var latest = runs.MaxBy(r => r.RunAt)!;
        var machines = string.Join("; ", runs.Select(r => r.Processor).Distinct());
        return $"Last updated {latest.RunAt:yyyy-MM-dd HH:mm} UTC on top of commit {latest.Commit} · BenchmarkDotNet {latest.Job} job · '{latest.Dataset}' dataset · {machines} · {latest.Runtime}";
    }

    private static string Ratio(ResultRecord row, List<ResultRecord> engineRows)
    {
        var baseline = engineRows.FirstOrDefault(r => r.Baseline);
        return baseline is null ? "n/a" : Format.Ratio(row.MeanNs / baseline.MeanNs);
    }

    private static IEnumerable<string> OrderedApproaches(IEnumerable<string> approaches)
    {
        var order = Approaches.Descriptions.Keys.ToList();
        return approaches.Distinct().OrderBy(a => order.IndexOf(a) is var i && i < 0 ? int.MaxValue : i);
    }

    private static string Title(string engine) => EngineTitles.GetValueOrDefault(engine, engine);

    // GitHub heading anchor for "### Querying/SingleById (N=20)"
    private static string Anchor(string key) =>
        new string(key.ToLowerInvariant().Where(c => char.IsLetterOrDigit(c) || c is ' ' or '-' or '_').ToArray()).Replace(' ', '-');
}
